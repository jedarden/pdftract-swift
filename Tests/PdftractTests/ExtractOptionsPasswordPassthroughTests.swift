    /// Password the fixture was generated with (see above). The tests use it
    /// verbatim so a reader can reproduce the decryption outside the SDK:
    /// `echo test | pdftract extract --json - --password-stdin <fixture>`.
    private static let fixturePassword = "test"

    /// Materializes the embedded fixture to a fresh directory and asserts it
    /// is still a genuine encrypted PDF (trailer `/Encrypt` reference and a
    /// standard-handler dictionary present in the bytes).
    private func materializeEncryptedFixture() throws -> (directory: URL, path: String) {
        let directory = FileManager.default.temporaryDirectory
            .appendingPathComponent("pdftract-password-fixture-\(UUID().uuidString)", isDirectory: true)
        try FileManager.default.createDirectory(at: directory, withIntermediateDirectories: true)

        // .ignoreUnknownCharacters because the constant is a multi-line
        // literal: Foundation's strict base64 decode rejects the line breaks.
        guard let bytes = Data(
            base64Encoded: Self.encryptedFixtureBase64,
            options: .ignoreUnknownCharacters
        ) else {
            XCTFail("embedded encrypted-fixture base64 failed to decode")
            throw NSError(domain: "fixture", code: 1)
        }

        let pdf = directory.appendingPathComponent("encrypted.pdf")
        try bytes.write(to: pdf)

        let raw = String(decoding: bytes.prefix(4096), as: UTF8.self)
        XCTAssertTrue(raw.contains("%PDF-"), "fixture is not a PDF")
        XCTAssertTrue(
            raw.contains("/Encrypt"),
            "fixture lost its /Encrypt trailer entry — the embedded constant no longer carries an encrypted PDF"
        )
        XCTAssertTrue(
            raw.contains("/Standard"),
            "fixture lost its standard security handler — the embedded constant no longer carries an encrypted PDF"
        )

        return (directory, pdf.path)
    }

    // MARK: Argv- and stdin-capturing stub

    /// Minimal `Document` JSON the buffered-path stub prints: an empty page
    /// list is enough for `extract`, `extractText`, and `extractMarkdown` to
    /// decode successfully — none of the tests assert decoded content, only
    /// what the child received.
    private static let minimalDocumentJSON =
        #"{"schema_version":"1.0","pages":[],"metadata":{"page_count":0}}"#

    /// Minimal `Page` NDJSON line the streaming-path stub prints, so the
    /// drained stream yields exactly one page — proving the child ran to
    /// completion (and therefore consumed stdin) before the test reads the
    /// captured bytes.
    private static let minimalPageNDJSON =
        #"{"page_index":0,"width":612,"height":792,"rotation":0,"spans":[],"blocks":[]}"#

    /// Writes an executable stub `pdftract` that records its argv one
    /// argument per line into `<directory>/captured-argv.txt`, optionally
    /// drains its entire stdin verbatim into `<directory>/captured-stdin.bin`
    /// (`readsStdin`, below, explains why the negative tests turn this off),
    /// optionally writes `stderr` to stderr, and exits with `exitCode`.
    ///
    /// `readsStdin: true` is safe only for calls where the SDK wires a stdin
    /// pipe with the write end closed pre-launch — the `--password-stdin`
    /// path — because then the stub's read hits EOF deterministically. Any
    /// other call inherits the test process's stdin, which never EOFs, and
    /// the stub would hang the suite.
    private static func writeCapturingStub(
        stdout: String,
        exitCode: Int = 0,
        stderr: String = "",
        readsStdin: Bool
    ) throws -> (directory: URL, binaryPath: String, capturePath: String, stdinCapturePath: String) {
        let directory = FileManager.default.temporaryDirectory
            .appendingPathComponent("pdftract-password-passthrough-\(UUID().uuidString)", isDirectory: true)
        try FileManager.default.createDirectory(at: directory, withIntermediateDirectories: true)

        let captureURL = directory.appendingPathComponent("captured-argv.txt")
        let stdinCaptureURL = directory.appendingPathComponent("captured-stdin.bin")
        let binaryPath = directory.appendingPathComponent("pdftract").path

        var script = "#!/bin/sh\n"
        script += "printf '%s\\n' \"$@\" > '\(captureURL.path)'\n"
        if readsStdin {
            // Verbatim capture: the assertion compares raw bytes, so the
            // trailing newline the CLI contract expects must survive.
            script += "cat > '\(stdinCaptureURL.path)'\n"
        }
        if !stderr.isEmpty {
            script += "cat <<'PDFTRACT_STUB_STDERR_EOF' >&2\n\(stderr)\nPDFTRACT_STUB_STDERR_EOF\n"
        }
        // Quoted delimiter: the payload must pass through untouched.
        script += "cat <<'PDFTRACT_STUB_EOF'\n\(stdout)\nPDFTRACT_STUB_EOF\n"
        if exitCode != 0 {
            script += "exit \(exitCode)\n"
        }

        try script.write(toFile: binaryPath, atomically: true, encoding: .utf8)
        try FileManager.default.setAttributes([.posixPermissions: 0o755], ofItemAtPath: binaryPath)
        return (directory, binaryPath, captureURL.path, stdinCaptureURL.path)
    }

    /// Reads back the argv the stub recorded. Arguments arrive one per line;
    /// every argument these tests produce is newline-free, so the line split
    /// is lossless.
    private static func capturedArguments(from capturePath: String) throws -> [String] {
        let raw = try String(contentsOfFile: capturePath, encoding: .utf8)
        return raw
            .split(separator: "\n", omittingEmptySubsequences: true)
            .map(String.init)
    }

    /// Reads back the exact stdin bytes the stub captured.
    private static func capturedStdin(from path: String) throws -> Data {
        try Data(contentsOf: URL(fileURLWithPath: path))
    }

    /// Drives one buffered-path call against the stub and returns the argv
    /// plus stdin bytes the child received.
    private func capturedBufferedIO(
        stdout: String,
        exitCode: Int = 0,
        stderr: String = "",
        _ call: (Pdftract) async throws -> Void
    ) async throws -> (argv: [String], stdin: Data) {
        let stub = try Self.writeCapturingStub(
            stdout: stdout,
            exitCode: exitCode,
            stderr: stderr,
            readsStdin: true
        )
        defer { try? FileManager.default.removeItem(at: stub.directory) }

        try await call(Pdftract(binaryPath: stub.binaryPath))
        return (
            argv: try Self.capturedArguments(from: stub.capturePath),
            stdin: try Self.capturedStdin(from: stub.stdinCapturePath)
        )
    }

    /// Same, for calls expected to fail: returns the thrown `PdftractError`
    /// after asserting the call did throw one.
    private func capturedBufferedFailure(
        stdout: String,
        exitCode: Int,
        stderr: String,
        _ call: (Pdftract) async throws -> Void
    ) async throws -> (error: PdftractError, argv: [String], stdin: Data) {
        let stub = try Self.writeCapturingStub(
            stdout: stdout,
            exitCode: exitCode,
            stderr: stderr,
            readsStdin: true
        )
        defer { try? FileManager.default.removeItem(at: stub.directory) }

        let client = Pdftract(binaryPath: stub.binaryPath)
        do {
            try await call(client)
            XCTFail("expected the call to fail with exit code \(exitCode)")
            throw NSError(domain: "expected-failure", code: 1)
        } catch let error as PdftractError {
            return (
                error: error,
                argv: try Self.capturedArguments(from: stub.capturePath),
                stdin: try Self.capturedStdin(from: stub.stdinCapturePath)
            )
        }
    }

    /// Drives the streaming path against the stub and returns the argv plus
    /// stdin bytes the child received, after draining the stream to
    /// completion (a failed drain fails the test via `for try await`).
    private func capturedStreamIO(
        _ call: (Pdftract) async throws -> Void
    ) async throws -> (argv: [String], stdin: Data) {
        let stub = try Self.writeCapturingStub(
            stdout: Self.minimalPageNDJSON,
            readsStdin: true
        )
        defer { try? FileManager.default.removeItem(at: stub.directory) }

        try await call(Pdftract(binaryPath: stub.binaryPath))
        return (
            argv: try Self.capturedArguments(from: stub.capturePath),
            stdin: try Self.capturedStdin(from: stub.stdinCapturePath)
        )
    }

    // MARK: Buffered exec path

    /// The README "Encrypted PDFs" example verbatim (`password: "test"`, the
    /// fixture's own password) against the real encrypted fixture must reach
    /// the child as `--password-stdin` — and the password itself must arrive
    /// on stdin as one newline-terminated line, never in argv.
    func testExtractCarriesPasswordOverStdinNotArgv() async throws {
        let fixture = try materializeEncryptedFixture()
        defer { try? FileManager.default.removeItem(at: fixture.directory) }

        let (argv, stdin) = try await capturedBufferedIO(stdout: Self.minimalDocumentJSON) { client in
            _ = try await client.extract(
                .path(fixture.path),
                options: ExtractOptions(password: Self.fixturePassword)
            )
        }

        XCTAssertEqual(
            argv,
            ["extract", "--json", "--password-stdin", "--", fixture.path],
            "extract() with a password sent \(argv) — expected --password-stdin before the -- separator and no password value anywhere in argv"
        )
        XCTAssertFalse(
            argv.contains(Self.fixturePassword),
            "the password leaked into argv, where ps exposes it to every user on the machine"
        )
        XCTAssertEqual(
            String(decoding: stdin, as: UTF8.self),
            "\(Self.fixturePassword)\n",
            "the child must receive the password as one newline-terminated line on stdin (the --password-stdin contract)"
        )
    }

    /// The remediation loop the error table documents: a wrong-password run
    /// maps to `EncryptionError` (exit 3), which is the caller's cue to
    /// retry with `ExtractOptions(password:)`. The stub plays the CLI's
    /// encrypted-PDF failure so the mapping is exercised against the real
    /// fixture path; the exit code — not stderr prose — is the contract.
    func testWrongPasswordSurfacesAsEncryptionErrorWithRemediationRetrying() async throws {
        let fixture = try materializeEncryptedFixture()
        defer { try? FileManager.default.removeItem(at: fixture.directory) }

        // Leg 1: wrong password → EncryptionError (exit 3).
        let failure = try await capturedBufferedFailure(
            stdout: "",
            exitCode: 3,
            stderr: "Error: PDF is encrypted and the password is missing or wrong"
        ) { client in
            _ = try await client.extract(
                .path(fixture.path),
                options: ExtractOptions(password: "definitely-wrong")
            )
        }
        XCTAssertEqual(failure.error.exitCode, 3, "exit 3 must map to EncryptionError")
        XCTAssertTrue(
            failure.error.message.contains("encrypted"),
            "the CLI's stderr must reach the caller verbatim; got: \(failure.error.message)"
        )
        XCTAssertTrue(failure.argv.contains("--password-stdin"))

        // Leg 2: the retry with the right password succeeds — same stub
        // behavior except the exit code, i.e. the documented loop closes.
        let stub = try Self.writeCapturingStub(
            stdout: Self.minimalDocumentJSON,
            readsStdin: true
        )
        defer { try? FileManager.default.removeItem(at: stub.directory) }
        try await Pdftract(binaryPath: stub.binaryPath).extract(
            .path(fixture.path),
            options: ExtractOptions(password: Self.fixturePassword)
        )
        XCTAssertEqual(
            try Self.capturedStdin(from: stub.stdinCapturePath),
            Data("\(Self.fixturePassword)\n".utf8)
        )
    }

    /// A default-constructed `ExtractOptions` — every call that does not opt
    /// into decryption — must omit `--password-stdin` entirely, leaving the
    /// non-password argv unchanged. Serialization is inlined per consumer,
    /// so this pins the buffered path's omission half.
    func testDefaultExtractOptionsOmitPasswordFlag() async throws {
        let fixture = try materializeEncryptedFixture()
        defer { try? FileManager.default.removeItem(at: fixture.directory) }

        let stub = try Self.writeCapturingStub(
            stdout: Self.minimalDocumentJSON,
            readsStdin: false
        )
        defer { try? FileManager.default.removeItem(at: stub.directory) }

        try await Pdftract(binaryPath: stub.binaryPath).extract(
            .path(fixture.path),
            options: ExtractOptions()
        )

        let argv = try Self.capturedArguments(from: stub.capturePath)
        XCTAssertEqual(
            argv,
            ["extract", "--json", "--", fixture.path],
            "default ExtractOptions must omit --password-stdin; extract() sent \(argv)"
        )
        XCTAssertFalse(argv.contains("--password-stdin"), "default options leaked --password-stdin")
    }

    /// `password: ""` is documented as unset (README "Encrypted PDFs"): the
    /// CLI already tries the empty password per the PDF spec, so an explicit
    /// empty string must not flip the flag on.
    func testEmptyPasswordMeansUnset() async throws {
        let fixture = try materializeEncryptedFixture()
        defer { try? FileManager.default.removeItem(at: fixture.directory) }

        let stub = try Self.writeCapturingStub(
            stdout: Self.minimalDocumentJSON,
            readsStdin: false
        )
        defer { try? FileManager.default.removeItem(at: stub.directory) }

        try await Pdftract(binaryPath: stub.binaryPath).extract(
            .path(fixture.path),
            options: ExtractOptions(password: "")
        )

        let argv = try Self.capturedArguments(from: stub.capturePath)
        XCTAssertFalse(
            argv.contains("--password-stdin"),
            "an empty password must serialize as no password; extract() sent \(argv)"
        )
    }

    // MARK: The other buffered consumers

    /// `extractText` interleaves `--text`/`--json` after the options; the
    /// password flag and stdin line must survive that interleaving.
    func testExtractTextCarriesPasswordOverStdin() async throws {
        let fixture = try materializeEncryptedFixture()
        defer { try? FileManager.default.removeItem(at: fixture.directory) }

        let (argv, stdin) = try await capturedBufferedIO(stdout: Self.minimalDocumentJSON) { client in
            _ = try await client.extractText(
                .path(fixture.path),
                options: ExtractOptions(password: Self.fixturePassword)
            )
        }

        XCTAssertEqual(
            argv,
            ["extract", "--password-stdin", "--text", "--json", "--", fixture.path],
            "extractText() sent \(argv)"
        )
        XCTAssertEqual(String(decoding: stdin, as: UTF8.self), "\(Self.fixturePassword)\n")
    }

    /// `extractMarkdown` same contract with `--md`.
    func testExtractMarkdownCarriesPasswordOverStdin() async throws {
