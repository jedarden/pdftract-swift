    // MARK: Streaming path

    /// `extractStream` re-runs the serialization and spawn on its own inline
    /// path, so it gets its own stdin wiring — proven here end to end: the
    /// stub reads stdin before printing its page line, so a yielded page
    /// proves the child consumed (and received) the password line.
    func testExtractStreamCarriesPasswordOverStdin() async throws {
        let fixture = try materializeEncryptedFixture()
        defer { try? FileManager.default.removeItem(at: fixture.directory) }

        var pages = 0
        let (argv, stdin) = try await capturedStreamIO { client in
            for try await _ in client.extractStream(
                .path(fixture.path),
                options: ExtractOptions(password: Self.fixturePassword)
            ) {
                pages += 1
            }
        }
        XCTAssertEqual(pages, 1, "the stub's single page must be yielded")

        XCTAssertEqual(
            argv,
            ["extract", "--ndjson", "--password-stdin", "--", fixture.path],
            "extractStream() sent \(argv)"
        )
        XCTAssertEqual(String(decoding: stdin, as: UTF8.self), "\(Self.fixturePassword)\n")
    }
