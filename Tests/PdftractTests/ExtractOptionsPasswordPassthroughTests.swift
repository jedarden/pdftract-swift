//
// Passthrough tests for the encrypted-PDF password path
// (`ExtractOptions(password:)` fed to the four `extract` family methods),
// which README.md documents in "Encrypted PDFs" as the way a caller reaches
// the remediation the error table promises for `EncryptionError` (CLI exit
// 3, "password is missing/wrong").
//
// Hand-written, not generated: this file is not a codegen template output,
// so `pdftract sdk codegen` leaves it alone (the generator only writes files
// that exist in templates/sdk-skeleton/swift and never deletes unknown
// ones) — the same standing as ExtractOptionsOcrPassthroughTests.swift,
// which this file deliberately mirrors. Keep it that way.
//
// Provenance note (pdfswift-9359c9ca): the `password` field and the
// pre-launch stdin transport were added directly to the tree's generated
// `Types.swift`/`Methods.swift` because the Swift generator templates live
// in another repository this work could not touch. Until the same change is
// ported to `templates/sdk-skeleton/swift` there, a regeneration from the
// current templates would DROP the field — and this suite is the tripwire
// that makes that loud instead of silent, exactly the drift-gate role the
// OCR passthrough suite plays for its flags.
//
// What is pinned: the argv and the stdin bytes each consumer hands to the
// spawned pdftract process. The tests drive an argv-and-stdin-capturing
// stub `pdftract` binary (same fake-binary pattern as
// ExtractOptionsOcrPassthroughTests) that records its argv one-per-line and
// its entire stdin verbatim, then exits 0 with a minimal valid payload, so
// the assertions see exactly what the child received: flag spelling
// (`--password-stdin`), its position before the `--` separator, and the
// password arriving as one newline-terminated line on stdin — never in
// argv. That last property is the security half of the contract: the CLI's
// argv channel for passwords (`--password VALUE`) is rejected by the binary
// unless `PDFTRACT_INSECURE_CLI_PASSWORD=1` (exit 64), and argv is exposed
// to every user on the machine via `ps`, so a password that leaks into argv
// would be both nonfunctional and a disclosure.
//
// The fixture is a real encrypted PDF, not a stand-in: an RC4-40 (security
// handler R=2) document with user password `test`, generated by the pdftract
// repository's own fixture chain (`qpdf --encrypt test "" 2` over its
// `create_simple_base_pdf()`, saved as
// `crates/pdftract-core/tests/document_model/fixtures/encrypted_rc4_test.pdf`)
// and embedded here byte-identical as base64. `materializeEncryptedFixture`
// asserts the decoded bytes still carry a `/Encrypt` reference and a
// standard-handler object, so replacing the constant with a plain PDF —
// which would drain the "against an encrypted fixture" property from every
// test below — fails here loudly.
//
// Why there is no real-binary leg (mirroring the OCR suite's honest-gap
// note): it is currently impossible on two independent grounds, both
// reproduced 2026-11-25. First, the standing argv protocol mismatch
// (pdfswift-ccccb2ff): every available binary parses `--json` as a
// value-taking flag, so the SDK's `extract --json <input>` shape dies in
// clap before any password handling runs — reproduced against the v1.2.0
// musl release asset (sha256 f86d7274…) and the lineage binaries on this
// host. Second, even under the binary's own argv shape the v1.2.0 release
// never surfaces exit 3 on any document_model encrypted fixture (RC4-40,
// AES-128, AES-256): a missing or wrong password exits 0 and yields a
// document with zero text blocks, so neither the error leg nor a
// decrypts-and-round-trips leg can be asserted against it. The
// stub-based tests below therefore pin the SDK-side contract, and the
// end-to-end encrypted round-trip stays tracked with the protocol repair on
// pdfswift-ccccb2ff. The exit-3 mapping itself (the remediation entry
// point) is additionally covered stub-side here, against the real fixture.
//
// Negative tests use an argv-only stub because a stdin-reading stub would
// block on the inherited stdin of the test process: `--password-stdin` is
// precisely the flag that tells the CLI to read stdin, so its absence is
// the argv assertion, and the SDK wires a stdin pipe on exactly the same
// condition (one code path feeding both).
//

