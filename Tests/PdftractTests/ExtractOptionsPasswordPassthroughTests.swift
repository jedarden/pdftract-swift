        let (argv, stdin) = try await capturedBufferedIO(stdout: Self.minimalDocumentJSON) { client in
            _ = try await client.extractMarkdown(
                .path(fixture.path),
                options: ExtractOptions(password: Self.fixturePassword)
            )
        }

        XCTAssertEqual(
            argv,
            ["extract", "--password-stdin", "--md", "--json", "--", fixture.path],
